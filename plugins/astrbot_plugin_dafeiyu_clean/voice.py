"""她知道自己会发语音：给模型看的两段话。只依赖标准库，方便单独测。

AstrBot 的语音是在回复已经写好之后才掷骰子转的（result_decorate 阶段，分段之后、发出去之前），
存进聊天记录的还是那段文字，人格里也没提语音，所以她以为自己只会打字（10-28 实测：
回了三条语音后被夸「你声音真好听」，她用语音说「我打字呢，哪来的声音」；再问那条语音说了啥，她说「没有语音啊」）。
"""

_CN = {2: "两", 3: "三", 4: "四", 5: "五", 6: "六", 7: "七", 8: "八", 9: "九", 10: "十"}


def how_often(rate: float) -> str:
    """语音概率换成一句人话。"""
    if rate >= 0.95:
        return "你的回复都会"
    if rate > 0.6:
        return "你的回复多半会"
    n = max(2, round(1 / rate)) if rate > 0 else 10
    return f"你的回复大约{_CN.get(n, str(n))}条里有一条会"


def voice_prompt(rate: float) -> str:
    """追加到系统提示末尾的一段，按语音现在开没开二选一，所以人格文件里不用写、也不能写死。
    没开语音也要说一句：不说的话被问「你会发语音吗」，她照样张口就是「会啊」（10-28 实测，关了语音的会话里）。"""
    if rate <= 0:
        return (
            "\n\n【你现在不发语音】\n"
            "- 这里没开语音，你的回复都是文字，发不了语音。有人问你会不会发语音、想听你的声音，就照实说现在没开，别说自己会发。"
        )
    return (
        "\n\n【你会发语音】\n"
        f"- {how_often(rate)}被自动念成语音发出去，对方听到的就是你的声音，其余的是文字。哪条变成语音是随机的，你自己挑不了。\n"
        "- 被夸声音好听、被问刚才那条语音说了啥，就照常接话。别说自己只会打字、没有声音、发不了语音。\n"
        "- 有人让你发条语音，可以说看运气，别打包票。\n"
        "- 对话里方括号写的「你上一条回复是念成语音发出去的」是真的，那条对方听到的是你的声音。"
    )


def voice_note(said: list[str], limit: int = 120) -> str:
    """上一条回复念成了语音：追加在下一条用户消息后面（跟着存进聊天记录，之后几轮也看得到）。"""
    text = " ".join(s.strip() for s in said if s and s.strip())
    if len(text) > limit:
        text = text[:limit] + "…"
    return f"[你上一条回复是念成语音发出去的，对方听到你的声音说：「{text}」]"
